-- readings.lua
-- Which reading of each character a candidate's annotation shows.
--
-- A reverse dictionary returns a character's readings in code order, so the
-- first is the alphabetically smallest, not the commonest: 長 gives chang2
-- before zhang3, 樂 gives lok3 before lok6. It has no entry for a phrase.
-- The filters therefore choose here, in this order:
--
--   1. What was typed. A syllable the user typed for a character rules out
--      that character's other readings. A syllable that spells none of them
--      (an abbreviation, a typo) says nothing and is ignored.
--   2. A phrase from reading_tables, matched from the left, longest first,
--      unless it contradicts what was typed.
--   3. The character's readings by dictionary weight: the order in
--      reading_tables when the character is listed there, the reverse
--      dictionary's order otherwise.
--
-- A character with no reading gets no entry in the result, and join() shows
-- M.placeholder for it, so the readings stay aligned with the characters.
--
-- reading_tables is generated by rime/reading_tables.py from the locked
-- dictionaries and holds only what changes an answer. Its resolve() mirrors
-- steps 2 and 3 to decide what to leave out; change the two together.

local romanization = require('romanization')

local M = {}

M.placeholder = '?'

-- The characters of a UTF-8 string. The locked librime-lua links Lua 5.2,
-- which has no utf8 library, and a host's own build may link another Lua.
function M.chars(text)
  local chars = {}
  for char in text:gmatch('[\1-\127\194-\244][\128-\191]*') do
    chars[#chars + 1] = char
  end
  return chars
end

local function split(text)
  local words = {}
  for word in text:gmatch('%S+') do
    words[#words + 1] = word
  end
  return words
end

-- A character's codes from a reverse dictionary, in the dictionary's order.
function M.codes(reverse, char)
  if not reverse then
    return {}
  end
  local ok, found = pcall(reverse.lookup, reverse, char)
  if not ok or not found then
    return {}
  end
  return split(found)
end

function M.toneless(code)
  return (code:gsub('%d+$', ''))
end

-- The first of `codes` that spells `syllable`, or nil.
function M.spelled(codes, syllable)
  for _, code in ipairs(codes) do
    if M.toneless(code) == syllable then
      return code
    end
  end
  return nil
end

-- The syllables of a Pinyin preedit such as "zhang da" or "xi'an", spelled
-- as the dictionaries spell them (lüe is lve). Nil unless there is one per
-- character, which is the only case where they can be told apart.
function M.typed_pinyin(preedit, count)
  if not preedit then
    return nil
  end
  local syllables = {}
  for syllable in preedit:lower():gsub('ü', 'v'):gmatch("[^%s']+") do
    syllables[#syllables + 1] = syllable
  end
  if #syllables ~= count then
    return nil
  end
  return syllables
end

local Resolver = {}
Resolver.__index = Resolver

local no_tables = { max_phrase_length = 1, ranked = {}, phrases = {} }

-- `reverse` is a ReverseLookup or nil; `tables` is one language's entry in
-- reading_tables or nil.
function M.resolver(reverse, tables)
  return setmetatable({ reverse = reverse, tables = tables or no_tables }, Resolver)
end

function Resolver:ranked(char)
  local listed = self.tables.ranked[char]
  if listed then
    return split(listed)
  end
  return M.codes(self.reverse, char)
end

-- The listed phrase that starts at `first`, as an array of readings, unless
-- a typed syllable contradicts it.
function Resolver:phrase(chars, first, wanted)
  local longest = math.min(self.tables.max_phrase_length, #chars - first + 1)
  for length = longest, 2, -1 do
    local listed = self.tables.phrases[table.concat(chars, '', first, first + length - 1)]
    local phrase = listed and split(listed)
    if phrase and #phrase == length then
      local agrees = true
      for offset = 1, length do
        local syllable = wanted[first + offset - 1]
        if syllable and M.toneless(phrase[offset]) ~= syllable then
          agrees = false
          break
        end
      end
      if agrees then
        return phrase
      end
    end
  end
  return nil
end

-- The reading of every character in `chars`, keyed by position; a character
-- without one has no key. `typed` is nil or one toneless syllable per
-- character.
function Resolver:resolve(chars, typed)
  local ranked, wanted = {}, {}
  for position, char in ipairs(chars) do
    ranked[position] = self:ranked(char)
    local syllable = typed and typed[position]
    if syllable and M.spelled(ranked[position], syllable) then
      wanted[position] = syllable
    end
  end

  local result = {}
  local position = 1
  while position <= #chars do
    local phrase = self:phrase(chars, position, wanted)
    if phrase then
      for offset, reading in ipairs(phrase) do
        result[position + offset - 1] = reading
      end
      position = position + #phrase
    else
      local codes = ranked[position]
      result[position] = wanted[position] and M.spelled(codes, wanted[position]) or codes[1]
      position = position + 1
    end
  end
  return result
end

-- `readings` for `count` characters as one string, or nil when no character
-- has one. `render` turns a reading into what is shown.
function M.join(readings, count, render)
  local shown = {}
  local any = false
  for position = 1, count do
    local reading = readings[position]
    if reading then
      any = true
      shown[position] = render and render(reading) or reading
    else
      shown[position] = M.placeholder
    end
  end
  return any and table.concat(shown, ' ') or nil
end

-- luna_pinyin has more readings than terra_pinyin but no tones. If only
-- Luna lists the spelling the user typed, show it without inventing a tone.
function M.mandarin(resolver, luna, chars, typed)
  local tonal = resolver:resolve(chars, typed)
  local shown = {}
  for position, char in ipairs(chars) do
    local syllable = typed and typed[position]
    local code = tonal[position]
    if code and (not syllable or M.toneless(code) == syllable) then
      shown[position] = romanization.convert_tones(code)
    else
      local plain = M.codes(luna, char)
      local spelled = syllable and M.spelled(plain, syllable)
      if spelled then
        shown[position] = spelled:gsub('v', 'ü')
      elseif code then
        shown[position] = romanization.convert_tones(code)
      elseif plain[1] then
        shown[position] = plain[1]:gsub('v', 'ü')
      end
    end
  end
  return M.join(shown, #chars)
end

-- The generated tables, or an empty table when they cannot be loaded: the
-- annotations then fall back to the reverse dictionary's order, and the
-- other Lua components keep working.
function M.tables()
  local ok, tables = pcall(require, 'reading_tables')
  if ok and type(tables) == 'table' then
    return tables
  end
  if log and log.error then
    log.error('reading_tables.lua did not load: ' .. tostring(tables))
  end
  return {}
end

return M
